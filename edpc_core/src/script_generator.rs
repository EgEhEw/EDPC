use crate::pack_inspector::VehicleInfo;
use rand::Rng;

#[derive(Debug, Clone)]
pub struct ScriptConfig {
    pub random_id: String,
    pub model_file_name: String,
    pub model_display_name: String,
    pub wire_tracking_reference: f32,
    pub no_wire_park_height: f32,
    pub enable_depot_park: bool,
    pub depot_park_height: f32,
    pub upper_threshold: f32,
    pub lower_threshold: f32,
    pub vehicles: Vec<VehicleInfo>,
}

impl ScriptConfig {
    pub fn new_random_id() -> String {
        const CHARSET: &[u8] = b"abcdefghjkmnpqrstuvwxyz23456789";
        let mut rng = rand::thread_rng();
        (0..8)
            .map(|_| {
                let idx = rng.gen_range(0..CHARSET.len());
                CHARSET[idx] as char
            })
            .collect()
    }

    pub fn new_random_display_name() -> String {
        const CHARSET: &[u8] = b"abcdefghjkmnpqrstuvwxyz23456789";
        let mut rng = rand::thread_rng();
        (0..5)
            .map(|_| {
                let idx = rng.gen_range(0..CHARSET.len());
                CHARSET[idx] as char
            })
            .collect()
    }

    pub fn base_id(&self) -> String {
        let clean = self.random_id.trim();
        let base = clean
            .trim_end_matches(".js")
            .trim_end_matches("_pantograph")
            .trim_end_matches("_panto");
        if base.is_empty() {
            if clean.is_empty() {
                "panto".to_string()
            } else {
                clean.to_string()
            }
        } else {
            base.to_string()
        }
    }

    pub fn script_filename(&self) -> String {
        format!("{}_pantograph.js", self.base_id())
    }

    pub fn script_id(&self) -> String {
        format!("{}_panto", self.base_id())
    }

    pub fn generate_javascript(&self) -> String {
        let panto_model_path = format!("mtr:panto/{}", self.model_file_name);
        let mut out = String::new();

        out.push_str("/*\n");
        out.push_str(" * Generated by EDPC (EgEhE's Dynamic Pantograph Configurator)\n");
        out.push_str(" * Copyright (c) 2026 EgEhE\n");
        out.push_str(" */\n\n");

        out.push_str("// ============================================================================\n");
        out.push_str("// 1. GENERAL PANTOGRAPH CONFIG\n");
        out.push_str("// ============================================================================\n");
        out.push_str(&format!("var PANTO_MODEL_PATH = \"{}\";\n", panto_model_path));
        out.push_str(&format!("var PANTO_MODEL_NAME = \"{}\";\n\n", self.model_display_name));

        out.push_str(&format!("var WIRE_TRACKING_REFERENCE = {:.4};\n", self.wire_tracking_reference));
        out.push_str(&format!("var NO_WIRE_PARK_HEIGHT = {:.4};\n\n", self.no_wire_park_height));

        out.push_str(&format!("var ENABLE_DEPOT_PARK = {};\n", if self.enable_depot_park { "true" } else { "false" }));
        out.push_str(&format!("var DEPOT_PARK_HEIGHT = {:.4};\n\n", self.depot_park_height));

        out.push_str(&format!("var pantoUpperTreshold = {:.1};\n", self.upper_threshold));
        out.push_str(&format!("var pantoLowerTreshold = {:.1};\n\n", self.lower_threshold));

        out.push_str("// ============================================================================\n");
        out.push_str("// 2. PANTOGRAPH VEHICLE CONFIG\n");
        out.push_str("// ============================================================================\n");
        out.push_str("var PANTO_VEHICLE_CONFIG = {\n");

        for v in &self.vehicles {
            if v.has_pantograph {
                out.push_str(&format!("    \"{}\": {{\n", v.id));
                out.push_str(&format!("        mountHeight: {:.3},\n", v.mount_height));
                out.push_str(&format!("        mountX: {:.3},\n", v.mount_x));
                out.push_str(&format!("        mountZ: {:.3},\n", v.mount_z));
                out.push_str(&format!("        rotationYDeg: {:.1},\n", v.rotation_y_deg));
                out.push_str(&format!("        wireDetectZ: {:.3},\n", v.wire_detect_z));
                out.push_str("    },\n");
            }
        }
        out.push_str("};\n\n");

        out.push_str("// ============================================================================\n");
        out.push_str("// SCRIPT LOGIC (AUTOMATED VIA EgEhELib)\n");
        out.push_str("// ============================================================================\n\n");

        out.push_str("var _libLoaded = false;\n");
        out.push_str("var _egeheLibWarningShown = false;\n\n");

        out.push_str("// Load from EgEhELib shared library resource pack\n");
        out.push_str("try {\n");
        out.push_str("    if (typeof Resources !== \"undefined\" && typeof Resources.id === \"function\") {\n");
        out.push_str("        var egeheLibId = Resources.id(\"egehelib:dynamic_panto_lib.js\");\n");
        out.push_str("        if (typeof Resources.exist === \"function\" && Resources.exist(egeheLibId)) {\n");
        out.push_str("            include(egeheLibId);\n");
        out.push_str("            _libLoaded = true;\n");
        out.push_str("        }\n");
        out.push_str("    }\n");
        out.push_str("} catch (e) {\n");
        out.push_str("    print(\"[Pantograph] Error including EgEhELib: \" + e);\n");
        out.push_str("}\n\n");

        out.push_str("function warnMissingEgEhELib() {\n");
        out.push_str("    if (_egeheLibWarningShown) return;\n");
        out.push_str("    try {\n");
        out.push_str("        if (typeof MinecraftClient !== \"undefined\") {\n");
        out.push_str("            var player = null;\n");
        out.push_str("            try {\n");
        out.push_str("                if (typeof MinecraftClient.localPlayer === \"function\") {\n");
        out.push_str("                    player = MinecraftClient.localPlayer();\n");
        out.push_str("                }\n");
        out.push_str("            } catch (e) {}\n");
        out.push_str("            if (player == null) {\n");
        out.push_str("                try {\n");
        out.push_str("                    var mc = Packages.org.mtr.mapping.holder.MinecraftClient.getInstance();\n");
        out.push_str("                    if (mc && mc.getPlayerMapped() != null) {\n");
        out.push_str("                        player = mc.getPlayerMapped();\n");
        out.push_str("                    }\n");
        out.push_str("                } catch (e) {}\n");
        out.push_str("            }\n");
        out.push_str("            if (player != null) {\n");
        out.push_str("                MinecraftClient.displayMessage(\n");
        out.push_str("                    \"§c[Pantograph] §e Seems like 'EgEhELib' is missing or not enabled! Please enable the EgEhELib Resource Pack for pantographs to work.\",\n");
        out.push_str("                    false\n");
        out.push_str("                );\n");
        out.push_str("                _egeheLibWarningShown = true;\n");
        out.push_str("                print(\"[Pantograph] Missing EgEhELib warning displayed in chat.\");\n");
        out.push_str("            }\n");
        out.push_str("        }\n");
        out.push_str("    } catch (e) {\n");
        out.push_str("        print(\"[Pantograph] Error displaying EgEhELib warning: \" + e);\n");
        out.push_str("    }\n");
        out.push_str("}\n\n");

        out.push_str("if (!_libLoaded) {\n");
        out.push_str("    print(\"[Pantograph] CRITICAL: dynamic_panto_lib.js could not be loaded from EgEhELib! Please make sure 'EgEhELib' resource pack is active.\");\n");
        out.push_str("    warnMissingEgEhELib();\n");
        out.push_str("}\n\n");

        out.push_str("// ============================================================================\n");
        out.push_str("// MODEL & RUNTIME ENGINE\n");
        out.push_str("// ============================================================================\n");
        out.push_str("var panto = typeof loadPantograph === \"function\" ? loadPantograph(PANTO_MODEL_PATH, PANTO_MODEL_NAME) : null;\n\n");

        out.push_str("function create(ctx, state, train) {\n");
        out.push_str("    if (!_libLoaded) {\n");
        out.push_str("        warnMissingEgEhELib();\n");
        out.push_str("        return;\n");
        out.push_str("    }\n");
        out.push_str("}\n\n");

        out.push_str("function render(ctx, state, train) {\n");
        out.push_str("    if (!_libLoaded) {\n");
        out.push_str("        warnMissingEgEhELib();\n");
        out.push_str("        return;\n");
        out.push_str("    }\n");
        out.push_str("    if (panto) {\n");
        out.push_str("        panto.renderAll(ctx, state, train, PANTO_VEHICLE_CONFIG);\n");
        out.push_str("    }\n");
        out.push_str("}\n");

        out
    }
}
